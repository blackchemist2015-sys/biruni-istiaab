def where_line(eqs):
    """Arabic 'where' paragraph for the symbols that occur in the converted equations of a figure."""
    txt = " ".join(eqs)
    found = []
    for rx, sym, term, d, f in SYMS:
        if re.search(rx, txt):
            found.append(f"${sym}$: {d}" + (f"، $({f})$" if f and f not in txt else ""))
    pts = sorted(set(re.findall(r"\\mathrm\{([A-Z]+)\}", txt)))
    if pts:
        inv = {v: k for k, v in LETTERS.items()}
        letters = sorted(set("".join(pts)))
        found.append("النقاط: " + "، ".join(f"$\\mathrm{{{c}}}$ = {inv[c]}" for c in letters if c in inv))
    return found

